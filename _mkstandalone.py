_BOLD = re.compile(r'\*\*(.+?)\*\*')


def md(t):
    """HTML 插入不解析 markdown：**x** 会原样留在正文里，这里转成 <b>x</b>。"""
    return _BOLD.sub(r'<b>\1</b>', t)


PS = ("font-family:SimSun;font-size:12pt;color:#111827;"
      "text-indent:2em;text-align:justify;line-height:170%;margin:0pt 0pt 6.6pt 0pt")
PS0 = ("font-family:SimSun;font-size:12pt;color:#111827;"
       "text-indent:0;text-align:left;line-height:170%;margin:0pt 0pt 4pt 0pt")
TH = ("background-color:#f9fafb;border:1px solid #e5e7eb;padding:6pt 9pt;"
      "font-family:SimSun;font-size:10pt;color:#111827;font-weight:bold;"
      "text-align:left;vertical-align:top")
# ★ 单元格必须显式 text-align:left：命名样式里的 jc 映射是反的（left->end），
#   不写这一句表格正文会被继承成右对齐（实测踩过）。
TD = ("border:1px solid #e5e7eb;padding:6pt 9pt;font-family:SimSun;"
      "font-size:10pt;color:#111827;vertical-align:top;text-align:left")
TB = "border-collapse:collapse;width:100%"
CB = ("background-color:#f3f4f6;border:1px solid #e5e7eb;padding:6pt;text-align:left")
CP = "margin:0pt 0pt 0pt 0pt;font-family:Consolas;font-size:9pt;color:#111827"
LI = ' style="text-align:left"'


class Doc(object):
    def __init__(self):
        self.out = []

    def raw(self, s):
        self.out.append(s)

    def h1(self, t):
        self.out.append('<h1>%s</h1>' % md(t))

    def h2(self, t):
        self.out.append('<h2>%s</h2>' % md(t))

    def h3(self, t):
        self.out.append('<h3>%s</h3>' % md(t))

    def p(self, text, indent=True):
        self.out.append('<p style="%s">%s</p>' % (PS if indent else PS0, md(text)))

    def ul(self, items):
        self.out.append('<ul>%s</ul>'
                        % ''.join('<li%s>%s</li>' % (LI, md(i)) for i in items))

    def ol(self, items):
        self.out.append('<ol>%s</ol>'
                        % ''.join('<li%s>%s</li>' % (LI, md(i)) for i in items))

    def table(self, headers, rows):
        h = ''.join('<th style="%s">%s</th>' % (TH, md(c)) for c in headers)
        body = ''.join('<tr>%s</tr>' % ''.join('<td style="%s">%s</td>' % (TD, md(c)) for c in r)
                       for r in rows)
        self.out.append('<table style="%s"><tr>%s</tr>%s</table>' % (TB, h, body))

    def code(self, lines):
        # 关键顺序: 先逐行转义, 再用 <br> 拼。反过来会把 <br> 自己转义成文本,
        # 结果整段代码挤成一行(实测踩过)。
        esc = []
        for ln in lines:
            esc.append(ln.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))
        self.out.append('<table style="%s"><tr><td style="%s"><pre style="%s">%s</pre>'
                        '</td></tr></table>' % (TB, CB, CP, '<br>'.join(esc)))

    def html(self):
        return ''.join(self.out)


def c(t):
    return '<code>%s</code>' % t


