d.h1('第 6 章 算法选择与距离平滑')
d.p('两种算法由一个函数统一封装，按 ' + c('DIST_MODE') + ' 分派：')
d.code([
    'def est_dist(b):',
    '    """按 DIST_MODE 选算法。返回 (距离 或 None, 是否可信, 方法代号 G/H)。',
    '',
    '    b = (x, y, w, h, prob)。底边 y+h 就是脚尖所在行。',
    '    """',
    '    if DIST_MODE != "HEIGHT":',
    '        d, ok = est_dist_ground(b[1] + b[3])',
    '        if ok or DIST_MODE == "GROUND":',
    '            return d, ok, "G"',
    '    d, ok = estimate_dist(b[3])        # 框高 = b[3]',
    '    return d, ok, "H"',
])
d.p('距离在跟踪器里做<b>跨帧指数平滑</b>，同一个 ID 的距离别跳：')
