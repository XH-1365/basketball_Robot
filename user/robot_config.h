#ifndef ROBOT_CONFIG_H
#define ROBOT_CONFIG_H

/* ==========================================================================
 * 1. 底盘速度环 PID
 * ==========================================================================
 * 四个 M3508 各跑一个独立速度环，编号与 chassis_solve.h 一致：
 *   [0] 一号 RB 右后 0x201
 *   [1] 二号 LB 左后 0x202
 *   [2] 三号 LF 左前 0x203
 *   [3] 四号 RF 右前 0x204
 *
 * "硬" = 响应快、跟手、抗干扰强；代价是容易抖/啸叫。
 *   - 想更硬：加大 KP，KD 跟着加一点防超调
 *   - 抖了/啸叫了：减 KP，或加 KD
 *   - 到不了目标转速（有静差）：加 KI
 */

/* 输出限幅：M3508(C620) 电调电流指令官方范围 ±16384，不要改 */
#define CHASSIS_3508_MAX_CURRENT   16384
/* 积分限幅：防止长时间静差把积分堆爆，导致松杆后车继续冲 */
#define CHASSIS_PID_MAX_IOUT       3000

/*
 * 基准参数（一号 RB / 三号 LF / 四号 RF）—— 决定行驶手感
 * 20261023 实测：原 KP=1.6 / KI=0.01 表现为提速肉 + 四轮静差消不掉跑偏。
 *   KP 1.6 -> 2.6：满误差时 P 输出从 20% 提到 32% 满电流，提速明显；
 *   KI 0.01 -> 0.08：100rpm 静差约 1.3s 补完（原来要 10s），各轮静差自然消除；
 *   KD 按原 KP:KD ≈ 0.75 的比例跟随。
 */
#define PID_BASE_KP        2.6f
#define PID_BASE_KI        0.08f
#define PID_BASE_KD        1.6f

/* 二号电机 LB（左后 0x202）—— 保持 1.5 倍相对硬度，单独一组 */
#define PID_2_KP           3.9f
#define PID_2_KI           0.08f
#define PID_2_KD           2.4f

/* ==========================================================================
 * 2. 松杆刹车
 * ==========================================================================
 * 现象：松开摇杆后车有惯性滑行。
 * 原因：1) KP 偏小制动力不足 2) 匀速时累积的积分残留继续推车
 *       3) KD 只在误差突变的第一拍起作用。
 * 对策：摇杆归零且车未停稳时 -> 清积分 + KP/KD 乘 CHASSIS_BRAKE_GAIN 强力拉回零速；
 *       四轮转速都低于 CHASSIS_BRAKE_EXIT_RPM 视为停稳，恢复正常增益。
 */
#define CHASSIS_BRAKE_GAIN      2.5f    /* KP/KD 放大倍数。3.5->2.5：已有斜坡限幅削掉阶跃，不需要那么狠 */
#define CHASSIS_BRAKE_EXIT_RPM  60      /* 四轮 |rpm| 都低于此值 = 停稳，退出刹车模式 */

/* ==========================================================================
 * 3. 轮速目标斜坡限幅（防打滑）
 * ==========================================================================
 * 20261023 SWD 实测：指令阶跃（0->2250rpm 一拍）+ 大力矩 -> 轮子破抓地打滑，
 * 稳态轮速 ±100~200rpm 摆动，超调最高 10.6%。
 * 对策：每拍（10ms）目标最多变化 WHEEL_SLEW_RPM_PER_TICK，0->2250 约 150ms。
 * 调法：还打滑就减小；起步肉/不跟手就加大。设 0 = 关闭斜坡（恢复阶跃）。
 */
#define WHEEL_SLEW_RPM_PER_TICK    150

/* ==========================================================================
 * 4. 三路无刷（LANRC DShot300，信号 TIM8_CH1~3 = PC6/PI6/PI7）
 * ==========================================================================
 * 操作：A 键（key2 bit0）按住 = 油门使能；方向键上/下（key1）调速档；
 *       松开 A 立即停车，速度档保留。
 *       key2 的 B 键（bit1）是 RC / FOLLOW 模式切换，与 A 键不冲突。
 *
 * 注意：本文件的数值只管「软件油门」，电机正反转不在这里改。
 *       要改转向请用 BLHeliSuite 写电调参数（Motor Direction -> Reversed）。
 */
#define ESC_RUN_THROTTLE   1.0f   /* 满档油门上限，0.0~1.0 */
#define ESC_SPEED_STEP     0.025f /* 每 ESC_SPEED_TICK_MS 调 2.5%，0->100% 约 2s */
#define ESC_SPEED_TICK_MS  50u    /* 调速档的节拍，单位 ms */
#define ESC_SPEED_INIT     0.3f   /* 上电初始油门档位，一按 A 即按此速度转（0.3 = 30%） */
#define ESC_RAMP_STEP      0.01f  /* 油门斜坡：每拍（10ms）变化 1%，0->100% 约 1s，升降同速 */

/* ==========================================================================
 * 5. 运行模式
 * ==========================================================================
 * key2 按下边沿在 RC <-> FOLLOW 之间切换，切换时清四轮 PID 积分防残留。
 *
 *   RC     = 蓝牙手柄遥控
 *   FOLLOW = K210 视觉跟随，当前只做朝向跟踪（vx = 0, vy = 0）
 *
 * 跟随模式要恢复追人（前后保持距离），改 user/k210_follow.h 里的
 * K210_FOLLOW_VX_ENABLE 为 1，距离参数在同一个文件里。
 */
#define MODE_RC      0u
#define MODE_FOLLOW  1u

/* ==========================================================================
 * 6. SWD 在线监控标识（一般不用改）
 * ==========================================================================
 * 双串口都被占用后（USART1 = 蓝牙，USART6 = K210），调试信息改走 SWD：
 * 主循环每拍刷新 V2_dbg，PC 端用 pyocd 不停机轮询读取。
 * magic 用来确认读到的地址/固件是配套版本，只有改了结构体布局才需要动它。
 */
#define V2_DBG_MAGIC 0x56324442u  /* 'V2DB' */

#endif /* ROBOT_CONFIG_H */
