def ul(items):
    out.append('<ul>%s</ul>' % ''.join('<li>%s</li>' % md(i) for i in items))


def ol(items):
    out.append('<ol>%s</ol>' % ''.join('<li>%s</li>' % md(i) for i in items))


def table(headers, rows):
    h = ''.join('<th style="%s">%s</th>' % (TH, md(c)) for c in headers)
    body = ''.join('<tr>%s</tr>' % ''.join('<td style="%s">%s</td>' % (TD, md(c)) for c in r)
                   for r in rows)
    out.append('<table style="%s"><tr>%s</tr>%s</table>' % (TB, h, body))


